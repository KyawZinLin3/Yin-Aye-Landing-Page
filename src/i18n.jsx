const LanguageContext = createContext({ language: 'en', setLanguage: () => {}, t: value => value });

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try { return localStorage.getItem('yinaye-language') === 'my' ? 'my' : 'en'; }
    catch { return 'en'; }
  });

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.classList.toggle('language-my', language === 'my');
    try { localStorage.setItem('yinaye-language', language); } catch {}
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: text => language === 'my' ? (translations[text] ?? text) : text,
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}
